const VARIANTS = (() => {
  const map = new Map<string, Set<string>>()
  for (const group of VARIANT_GROUPS) {
    const chars = Array.from(group)
    if (chars.length < 2) continue
    for (const ch of chars) {
      const set = map.get(ch) ?? new Set<string>()
      for (const other of chars) set.add(other)
      map.set(ch, set)
    }
  }
  return map
})()

/**
 * Return a copy of `pattern` in which every character that has script variants matches all of them.
 * Characters inside a bracket class get the variants appended to the class; characters outside one are
 * replaced by a small class. Escapes, groups, quantifiers and flags are preserved.
 */
export function hanTolerant(pattern: RegExp): RegExp {
  const source = pattern.source
  let out = ''
  let inClass = false
  // Index of the first character inside the current class (after `[` and an optional `^`).
  let classBody = 0
  for (let i = 0; i < source.length; i += 1) {
    const ch = source[i]
    if (ch === '\\') {
      // `\k<name>` names a group: copy the whole reference unchanged.
      if (source[i + 1] === 'k' && source[i + 2] === '<') {
        const end = source.indexOf('>', i + 3)
        const stop = end < 0 ? source.length - 1 : end
        out += source.slice(i, stop + 1)
        i = stop
        continue
      }
      out += ch + (source[i + 1] ?? '')
      i += 1
      continue
    }
    if (!inClass && ch === '(' && source[i + 1] === '?' && source[i + 2] === '<') {
      const next = source[i + 3]
      if (next !== '=' && next !== '!') {
        // `(?<name>`: copy the group name unchanged.
        const end = source.indexOf('>', i + 3)
        const stop = end < 0 ? source.length - 1 : end
        out += source.slice(i, stop + 1)
        i = stop
        continue
      }
    }
    if (inClass) {
      if (ch === ']') inClass = false
      const variants = VARIANTS.get(ch)
      // A literal range such as 一-十 must not be split by inserted characters. A hyphen first or
      // last in the class, or escaped, is a literal and makes no range.
      const rangeBefore =
        source[i - 1] === '-' && i - 1 > classBody && source[i - 2] !== '\\'
      const rangeAfter = source[i + 1] === '-' && source[i + 2] !== undefined && source[i + 2] !== ']'
      const isRangeEndpoint = rangeBefore || rangeAfter
      out += variants && !isRangeEndpoint ? Array.from(variants).join('') : ch
      continue
    }
    if (ch === '[') {
      inClass = true
      out += ch
      if (source[i + 1] === '^') {
        out += '^'
        i += 1
      }
      classBody = i + 1
      continue
    }
    const variants = VARIANTS.get(ch)
    out += variants ? `[${Array.from(variants).join('')}]` : ch
  }
  return new RegExp(out, pattern.flags)
}
